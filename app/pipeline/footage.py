"""Footage providers. Every provider returns Candidates with licence data; selection happens in run.py.

PexelsProvider / PixabayProvider are written from each service's public API docs and have NOT been run against the
live services in this repo's test environment (no network egress there). Run `scripts/check_providers.py` with your
keys before relying on them.
"""
from __future__ import annotations

import hashlib
import os
import re
import subprocess
from dataclasses import dataclass, field

import httpx

from ..errors import PipelineError
from .media import duration as probe_duration, ffprobe


class ProviderError(Exception):
    pass


@dataclass
class Candidate:
    id: str
    provider: str
    title: str
    tags: list[str]
    download_url: str
    page_url: str
    width: int
    height: int
    fps: float
    duration: float
    licence: str
    licence_url: str
    attribution: str
    creator: str | None = None
    ai_generated: bool = False
    watermarked: bool = False
    commercial_use: bool = True
    synthetic: bool = False
    fallback: bool = False

    @property
    def key(self) -> str:
        return f"{self.provider}:{self.id}"


class MockProvider:
    """Generates synthetic, moving test clips with ffmpeg. Needs no key; licence CC0 (we made them)."""
    name = "mock"

    def __init__(self, fail: bool = False, cache_dir: str = "/tmp"):
        self.fail = fail
        self.cache_dir = cache_dir

    def search(self, query: str, orientation: str, limit: int) -> list[Candidate]:
        if self.fail:
            raise ProviderError("mock provider forced to fail")
        words = re.findall(r"[a-z0-9]+", query.lower())
        out = []
        for i in range(min(limit, 4)):
            h = hashlib.sha1(f"{query}|{i}".encode()).hexdigest()
            out.append(Candidate(
                id=h[:12], provider="mock", title=f"{query} variant {i + 1}", tags=words,
                download_url=f"mock://{h[:12]}?q={'+'.join(words)}&i={i}", page_url="https://example.invalid/mock",
                width=960, height=540, fps=30.0, duration=6.0 + i, licence="CC0-1.0",
                licence_url="https://creativecommons.org/publicdomain/zero/1.0/",
                attribution="Synthetic test footage generated by the engine", synthetic=True))
        return out

    def fetch(self, c: Candidate, dest: str) -> None:
        h = int(c.id[:3], 16) % 360
        label = re.sub(r"[^A-Za-z0-9 ]", "", c.title)[:40]
        vf = f"hue=h={h},drawtext=text='{label}':fontcolor=white:fontsize=34:x=(w-text_w)/2:y=h-90:box=1:boxcolor=black@0.45"
        p = subprocess.run(["ffmpeg", "-y", "-v", "error", "-f", "lavfi", "-i",
                            f"testsrc2=s=960x540:r=30:d={c.duration}", "-vf", vf, "-c:v", "libx264", "-preset",
                            "ultrafast", "-crf", "30", "-pix_fmt", "yuv420p", dest], capture_output=True, text=True)
        if p.returncode:
            raise ProviderError(f"mock render failed: {p.stderr[-200:]}")


class PexelsProvider:
    """Pexels Videos API. Pexels licence: free for commercial use, no attribution required."""
    name = "pexels"

    def __init__(self, key: str, timeout: float):
        self.key, self.timeout = key, timeout

    def search(self, query: str, orientation: str, limit: int) -> list[Candidate]:
        if not self.key:
            raise ProviderError("PEXELS_API_KEY not set")
        try:
            r = httpx.get("https://api.pexels.com/videos/search", timeout=self.timeout,
                          headers={"Authorization": self.key},
                          params={"query": query, "orientation": orientation, "per_page": limit, "size": "medium"})
            r.raise_for_status()
            data = r.json()
        except (httpx.HTTPError, ValueError) as e:
            raise ProviderError(f"pexels request failed: {e.__class__.__name__}")
        out = []
        for v in data.get("videos", []):
            files = [f for f in v.get("video_files", []) if f.get("file_type") == "video/mp4" and f.get("width")]
            if not files:
                continue
            f = min(files, key=lambda f: abs(f["width"] - 1920) if f["width"] >= 1280 else 10_000 + abs(f["width"] - 1920))
            slug = v.get("url", "").rstrip("/").split("/")[-1]
            title = re.sub(r"-\d+$", "", slug).replace("-", " ")
            out.append(Candidate(
                id=str(v["id"]), provider="pexels", title=title, tags=re.findall(r"[a-z0-9]+", title.lower()),
                download_url=f["link"], page_url=v.get("url", ""), width=f["width"], height=f["height"],
                fps=float(f.get("fps") or 30), duration=float(v.get("duration") or 0),
                licence="Pexels License", licence_url="https://www.pexels.com/license/",
                attribution=f"Video by {v.get('user', {}).get('name', 'Pexels contributor')} on Pexels",
                creator=v.get("user", {}).get("name")))
        return out

    def fetch(self, c: Candidate, dest: str) -> None:
        _http_fetch(c.download_url, dest, self.timeout)


class PixabayProvider:
    """Pixabay Videos API. Pixabay Content License permits commercial use without attribution."""
    name = "pixabay"

    def __init__(self, key: str, timeout: float):
        self.key, self.timeout = key, timeout

    def search(self, query: str, orientation: str, limit: int) -> list[Candidate]:
        if not self.key:
            raise ProviderError("PIXABAY_API_KEY not set")
        try:
            r = httpx.get("https://pixabay.com/api/videos/", timeout=self.timeout,
                          params={"key": self.key, "q": query, "per_page": max(limit, 3), "safesearch": "true"})
            r.raise_for_status()
            data = r.json()
        except (httpx.HTTPError, ValueError) as e:
            raise ProviderError(f"pixabay request failed: {e.__class__.__name__}")
        out = []
        for h in data.get("hits", [])[:limit]:
            vids = h.get("videos", {})
            v = vids.get("large") or vids.get("medium") or vids.get("small")
            if not v or not v.get("url"):
                continue
            tags = [t.strip().lower() for t in h.get("tags", "").split(",") if t.strip()]
            out.append(Candidate(
                id=str(h["id"]), provider="pixabay", title=", ".join(tags), tags=re.findall(r"[a-z0-9]+", " ".join(tags)),
                download_url=v["url"], page_url=h.get("pageURL", ""), width=v.get("width", 0), height=v.get("height", 0),
                fps=30.0, duration=float(h.get("duration") or 0), licence="Pixabay Content License",
                licence_url="https://pixabay.com/service/license-summary/",
                attribution=f"Video by {h.get('user', 'Pixabay contributor')} on Pixabay", creator=h.get("user")))
        return out

    def fetch(self, c: Candidate, dest: str) -> None:
        _http_fetch(c.download_url, dest, self.timeout)


def _http_fetch(url: str, dest: str, timeout: float, max_mb: int = 200) -> None:
    try:
        with httpx.stream("GET", url, timeout=timeout, follow_redirects=True) as r:
            r.raise_for_status()
            size = 0
            with open(dest, "wb") as f:
                for chunk in r.iter_bytes(65536):
                    size += len(chunk)
                    if size > max_mb * 1024 * 1024:
                        raise ProviderError("clip too large")
                    f.write(chunk)
    except httpx.HTTPError as e:
        raise ProviderError(f"download failed: {e.__class__.__name__}")


def build_providers(settings) -> list:
    out = []
    for name in settings.footage_providers:
        if name == "pexels":
            out.append(PexelsProvider(settings.pexels_api_key, settings.http_timeout))
        elif name == "pixabay":
            out.append(PixabayProvider(settings.pixabay_api_key, settings.http_timeout))
        elif name == "mock":
            out.append(MockProvider(fail=os.environ.get("MOCK_PROVIDER_FAIL") == "1"))
    return out


def make_fallback_card(dest: str, text: str, seconds: float) -> None:
    """Animated title card used when no clip is relevant enough. Never black, never frozen."""
    label = re.sub(r"[^A-Za-z0-9 ,.!?%-]", "", text)[:60].replace("'", "").replace(":", "")
    vf = (f"drawtext=text='{label}':fontcolor=white:fontsize=40:x=(w-text_w)/2:y=(h-text_h)/2:"
          "box=1:boxcolor=black@0.35:boxborderw=18")
    src = f"gradients=s=960x540:r=30:d={seconds}:speed=0.02:c0=0x1d3557:c1=0x2a9d8f:c2=0x264653:nb_colors=3"
    p = subprocess.run(["ffmpeg", "-y", "-v", "error", "-f", "lavfi", "-i", src, "-vf", vf, "-c:v", "libx264",
                        "-preset", "ultrafast", "-crf", "28", "-pix_fmt", "yuv420p", dest], capture_output=True, text=True)
    if p.returncode:
        raise PipelineError("MEDIA_PROCESSING_FAILED", "could not build fallback card", details={"stderr": p.stderr[-300:]})


def verify_clip(path: str) -> dict:
    """Raise if the downloaded file is not a playable video."""
    info = ffprobe(path)
    v = next((s for s in info.get("streams", []) if s.get("codec_type") == "video"), None)
    d = probe_duration(path)
    if not v or d < 1.0:
        raise ProviderError("corrupted or too-short clip")
    return {"duration": d, "width": v.get("width"), "height": v.get("height")}
