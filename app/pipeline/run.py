logger = logging.getLogger("broll.pipeline")


@dataclass
class Ctx:
    settings: object
    stt: object
    tts: object
    planner: object
    providers: list
    storage: object


class JobState:
    def __init__(self):
        self.warnings: list[dict] = []
        self.used: set[str] = set()
        self.fail_counts: dict[str, int] = {}
        self.down: set[str] = set()
        self.timings: dict[str, float] = {}
        self.llm_calls = 0

    def warn(self, code: str, message: str, scene: int | None = None) -> None:
        self.warnings.append({"code": code, "scene": scene, "message": message})


def _score(c: Candidate, query: str, scene_secs: float) -> float:
    q = set(content_words(query))
    if not q:
        return 1.0
    meta = set(tokens(c.title)) | set(c.tags)
    raw = len(q & meta) / len(q)
    s = 1 + 4 * min(1.0, raw * 1.25)
    if c.duration and c.duration < scene_secs - 0.2:
        s -= 0.4  # would have to loop
    return round(max(1.0, s), 2)


def _provider_failed(st: JobState, name: str, err: str, scene: int) -> None:
    st.fail_counts[name] = st.fail_counts.get(name, 0) + 1
    st.warn("PROVIDER_FAILED", f"{name}: {err}", scene)
    if st.fail_counts[name] >= 2:
        st.down.add(name)
        st.warn("PROVIDER_DISABLED_FOR_JOB", f"{name} failed twice and is skipped for the rest of this job.", scene)


def select_clip(i: int, scene: Scene, plan, ctx: Ctx, st: JobState, orientation: str, clip_dir: str, work: str) -> dict:
    s = ctx.settings
    best_considered = 0
    for q in plan.queries[:3]:
        pool: list[tuple[float, Candidate, object]] = []
        for prov in ctx.providers:
            if prov.name in st.down:
                continue
            try:
                found = prov.search(q, orientation, 12)
            except ProviderError as e:
                _provider_failed(st, prov.name, str(e), i)
                continue
            for c in found:
                meta = set(tokens(c.title)) | set(c.tags)
                if c.key in st.used or not c.commercial_use or c.watermarked or (plan.avoid & meta):
                    continue
                pool.append((_score(c, q, scene.duration), c, prov))
        best_considered += len(pool)
        pool.sort(key=lambda x: -x[0])
        for score, c, prov in pool[:3]:
            if score < s.min_relevance:
                break
            path = os.path.join(clip_dir, f"{c.provider}_{c.id}.mp4")
            try:
                if not os.path.exists(path):
                    tmp = path[:-4] + f".{os.getpid()}.part.mp4"
                    prov.fetch(c, tmp)
                    verify_clip(tmp)
                    os.replace(tmp, path)
            except ProviderError as e:
                st.warn("CORRUPT_OR_FAILED_DOWNLOAD", f"{c.key}: {e}", i)
                _provider_failed(st, prov.name, str(e), i)
                for x in (path, path[:-4] + f".{os.getpid()}.part.mp4"):
                    if os.path.exists(x):
                        os.remove(x)
                continue
            st.used.add(c.key)
            looped = bool(c.duration) and c.duration < scene.duration - 0.2
            if looped:
                st.warn("CLIP_LOOPED", f"{c.key} is shorter than the scene and is looped.", i)
            return {"clip": c, "path": path, "score": score, "query": q, "considered": best_considered,
                    "reason": f"best of {len(pool)} candidates for query '{q}' (lexical relevance {score}/5)"}
    # nothing relevant enough: animated title card instead of a nonsense match
    st.warn("FALLBACK_CARD_USED", "No sufficiently relevant, licence-clean clip was found; used a title card.", i)
    card = os.path.join(work, f"card_{i}.mp4")
    make_fallback_card(card, scene.text, max(scene.duration, 1.5))
    c = Candidate(id=f"card{i}", provider="engine", title="title card", tags=[], download_url="", page_url="",
                  width=960, height=540, fps=30, duration=max(scene.duration, 1.5), licence="CC0-1.0",
                  licence_url="https://creativecommons.org/publicdomain/zero/1.0/",
                  attribution="Generated by the engine (no third-party footage)", synthetic=True, fallback=True)
    return {"clip": c, "path": card, "score": 1.0, "query": None, "considered": best_considered,
            "reason": "no candidate passed the relevance, licence and avoid-list filters; title card used"}


def _prepare_narration(job: dict, req: CreateJobRequest, kind: str, ctx: Ctx, st: JobState, work: str):
    s = ctx.settings
    narr = os.path.join(work, "narration.wav")
    if kind == "audio":
        src = job.get("input_path")
        hint = os.path.basename(src) if src else ""
        if not src:
            hint = urlparse(req.audio_url).path
            src = os.path.join(work, "input_audio")
            media.download(req.audio_url, src, s.max_download_mb, s.http_timeout, s.allow_private_urls)
        total = media.validate_audio(src, s.max_audio_seconds, hint if os.path.splitext(hint)[1] else "")
        media.norm_wav(src, narr)
        total = media.duration(narr)
        words = ctx.stt.transcribe(src, total)
        scenes = scenes_from_words(words, total, s.min_scene_seconds, s.max_scene_seconds)
        if not scenes:
            raise PipelineError("NO_SPEECH_DETECTED", "No speech detected.", 422)
        return narr, total, scenes, {"stt": ctx.stt.name, "stt_model": getattr(ctx.stt, "model", "")}
    # text path: synthesise each phrase separately so scene boundaries are exact
    if kind == "script":
        items = [(t, None) for t in phrases_from_text(req.script)]
    else:
        items = [(sc.text.strip(), sc.visual_hint) for sc in req.scenes if sc.text.strip()]
    wavs = []
    for n, (text, _hint) in enumerate(items):
        w = os.path.join(work, f"tts_{n}.wav")
        try:
            ctx.tts.synthesize(text, req.voice, w)
        except PipelineError:
            raise
        except Exception as e:
            raise PipelineError("PROVIDER_UNAVAILABLE", f"TTS failed: {e.__class__.__name__}", 503, retryable=True)
        wavs.append(w)
    durs = media.concat_wavs(wavs, narr)
    scenes, t = [], 0.0
    for n, ((text, hint), d) in enumerate(zip(items, durs)):
        scenes.append(Scene(index=n, text=text, start=t, end=t + d, visual_hint=hint))
        t += d
    return narr, t, scenes, {"tts": ctx.tts.name, "tts_model": getattr(ctx.tts, "model", ""),
                              "tts_chars": sum(len(x[0]) for x in items)}


def run_pipeline(job: dict, ctx: Ctx, progress) -> dict:
    s = ctx.settings
    st = JobState()
    t_all = time.time()
    req = CreateJobRequest(**job["request"])
    kind = req.input_kind(has_upload=bool(job.get("input_path")))
    os.makedirs(s.work_dir, exist_ok=True)
    clip_dir = os.path.join(s.cache_dir, "clips")
    seg_dir = os.path.join(s.cache_dir, "segments")
    os.makedirs(clip_dir, exist_ok=True)
    os.makedirs(seg_dir, exist_ok=True)
    work = tempfile.mkdtemp(prefix=job["job_id"] + "_", dir=s.work_dir)
    try:
        t = time.time()
        progress(5, "preparing narration")
        narr, total, scenes, narr_info = _prepare_narration(job, req, kind, ctx, st, work)
        st.timings["narration_s"] = round(time.time() - t, 2)
        log(logger, logging.INFO, "narration ready", scenes=len(scenes), seconds=round(total, 2), input=kind)
        progress(25, "planning scenes")

        t = time.time()
        plans = []
        for i, sc in enumerate(scenes):
            ctxt = " ".join(x.text for x in scenes[max(0, i - 1): i + 2])
            plan = ctx.planner.plan(sc.text, sc.visual_hint, ctxt, req.style, req.avoid)
            if plan.sensitive and plan.queries:  # vary the calm visuals from scene to scene
                k = i % len(plan.queries)
                plan.queries = plan.queries[k:] + plan.queries[:k]
            for f in plan.flags:
                st.warn(f["code"], f["message"], i)
            if getattr(plan, "llm_used", False):
                st.llm_calls += 1
            plans.append(plan)
        st.timings["planning_s"] = round(time.time() - t, 2)

        t = time.time()
        orientation = "portrait" if req.aspect_ratios == ["9:16"] else "landscape"
        chosen = []
        for i, (sc, plan) in enumerate(zip(scenes, plans)):
            chosen.append(select_clip(i, sc, plan, ctx, st, orientation, clip_dir, work))
            progress(25 + int(40 * (i + 1) / len(scenes)), f"footage {i + 1}/{len(scenes)}")
        st.timings["footage_s"] = round(time.time() - t, 2)

        # captions
        srt_text = build_srt(scenes)
        srt_path = os.path.join(work, "captions.srt")
        with open(srt_path, "w", encoding="utf-8") as f:
            f.write(srt_text)

        t = time.time()
        videos, qa = {}, []
        for r_i, ratio in enumerate(req.aspect_ratios):
            segs = []
            for sc, ch in zip(scenes, chosen):
                key = segment_key(ch["clip"].key + ("|" + sc.text if ch["clip"].fallback else ""),
                                  sc.duration, ratio, s.portrait_mode)
                seg = os.path.join(seg_dir, key + ".mp4")
                if not os.path.exists(seg):
                    tmp = seg + f".{os.getpid()}.{id(sc)}.part.mp4"
                    render_segment(ch["path"], sc.duration, ratio, s.portrait_mode, tmp)
                    os.replace(tmp, seg)
                segs.append(seg)
            out = os.path.join(work, f"video_{ratio_slug(ratio)}.mp4")
            assemble(segs, narr, srt_path, req.captions.burn_in, ratio, total, work, out)
            q = qa_check(out, total, ratio)
            if not q["passed"]:
                for name, ok in q["checks"].items():
                    if not ok:
                        st.warn("QA_CHECK_FAILED", f"{ratio}: {name}")
            qa.append(q)
            videos[ratio] = out
            progress(65 + int(25 * (r_i + 1) / len(req.aspect_ratios)), f"rendered {ratio}")
        st.timings["render_s"] = round(time.time() - t, 2)

        # timeline.json
        timeline = {"job_id": job["job_id"], "duration_s": round(total, 3), "input_kind": kind,
                    "relevance_method": "lexical overlap of the search query with provider metadata (heuristic, 1-5)",
                    "scenes": []}
        for sc, plan, ch in zip(scenes, plans, chosen):
            c: Candidate = ch["clip"]
            timeline["scenes"].append({
                "index": sc.index, "start": round(sc.start, 3), "end": round(sc.end, 3), "text": sc.text,
                "visual_hint": sc.visual_hint, "queries": plan.queries, "query_used": ch["query"],
                "flags": [f["code"] for f in plan.flags],
                "clip": {"id": c.id, "provider": c.provider, "title": c.title, "source_url": c.page_url or None,
                         "licence": c.licence, "licence_url": c.licence_url, "attribution": c.attribution,
                         "creator": c.creator, "commercial_use": c.commercial_use, "watermarked": c.watermarked,
                         "ai_generated": c.ai_generated, "synthetic_test_footage": c.synthetic and not c.fallback,
                         "fallback_title_card": c.fallback, "duration_s": c.duration},
                "reason": f"{ch['reason']}. Planner: {plan.reason}",
                "relevance_score": ch["score"]})

        # captions + files
        files = dict(videos={r: p for r, p in videos.items()})
        tl_path = os.path.join(work, "timeline.json")
        with open(tl_path, "w") as f:
            json.dump(timeline, f, indent=2)

        total_wall = time.time() - t_all
        licences = sorted({c["clip"]["licence"] for c in timeline["scenes"]})
        ffv = subprocess.run(["ffmpeg", "-version"], capture_output=True, text=True).stdout.split("\n")[0]
        manifest = {
            "job_id": job["job_id"], "app_version": s.app_version,
            "providers": {"narration": narr_info, "planner": {"name": ctx.planner.name, "model": getattr(ctx.planner, "model", s.llm_model)},
                          "footage": [p.name for p in ctx.providers]},
            "versions": {"python": platform.python_version(), "ffmpeg": ffv},
            "settings": {"aspect_ratios": req.aspect_ratios, "style": req.style, "avoid": req.avoid,
                         "voice": req.voice, "captions": req.captions.model_dump(), "fps": 30,
                         "sizes": {r: list(SIZES[r]) for r in req.aspect_ratios}, "portrait_mode": s.portrait_mode,
                         "min_scene_seconds": s.min_scene_seconds, "max_scene_seconds": s.max_scene_seconds,
                         "min_relevance": s.min_relevance},
            "seed": req.seed if req.seed is not None else 0,
            "determinism": "Selection is deterministic for the same inputs and provider results.",
            "timings_s": {**st.timings, "total_s": round(total_wall, 2)},
            "cost_estimate_usd": {
                "llm": round(st.llm_calls * s.cost_per_llm_call_usd, 5),
                "tts": round(narr_info.get("tts_chars", 0) * s.cost_per_tts_char_usd, 5),
                "footage": 0.0,
                "compute": round(total_wall / 3600 * s.compute_cost_per_hour_usd, 5),
                "note": "Estimate from configured unit prices, not billing data."},
            "rights": {"all_clips_commercial_use": all(c["clip"]["commercial_use"] for c in timeline["scenes"]),
                       "licences_used": licences,
                       "ai_generated_clips": sum(1 for c in timeline["scenes"] if c["clip"]["ai_generated"]),
                       "synthetic_test_clips": sum(1 for c in timeline["scenes"] if c["clip"]["synthetic_test_footage"]),
                       "fallback_title_cards": sum(1 for c in timeline["scenes"] if c["clip"]["fallback_title_card"])},
            "qa": qa, "warnings": st.warnings}
        mf_path = os.path.join(work, "manifest.json")
        with open(mf_path, "w") as f:
            json.dump(manifest, f, indent=2)

        progress(92, "uploading")
        jid = job["job_id"]
        urls = {"videos": {r: ctx.storage.put_file(f"{jid}/video_{ratio_slug(r)}.mp4", p) for r, p in videos.items()},
                "captions_srt": ctx.storage.put_file(f"{jid}/captions.srt", srt_path) if req.captions.srt else None,
                "timeline": ctx.storage.put_file(f"{jid}/timeline.json", tl_path),
                "manifest": ctx.storage.put_file(f"{jid}/manifest.json", mf_path)}
        return {"outputs": urls, "warnings": st.warnings, "duration_s": round(total, 2),
                "scene_count": len(scenes), "qa_passed": all(q["passed"] for q in qa)}
    finally:
        shutil.rmtree(work, ignore_errors=True)
